#!/usr/bin/env python3
"""Write docs/utopia/TABLES-A3b.md from the A3b browser-helper metrics.

Input: docs/utopia/data/a3b/<page>-<width>-<state>-<set>.json, written by
`python3 .orca/mission-runtime/browser.py metrics --selector ...` on the live pages:
  state  off   = live page as served (theme setting kc_fluid_type off: nothing loads)
         a3    = the reviewed A3 kc-fluid.css alone (f176627), for the split and the jump
         on    = docs/utopia/inject/fluid-on.css (kc_fluid_type on)
         wide  = docs/utopia/inject/fluid-on-wide.css (kc_fluid_type_wide on as well)
  set    head  = h1-h6, .h0-.h6, .text-xl
         body  = body, p (homepage)
         card  = body, Loop texts restyled in the buybox, mission card (PDP)
         mc    = mission card only (749/750 boundary)
off and on/wide of one width were measured on the same page load, so rows pair by index.

Run from the repo root:  python3 docs/utopia/tools/a3b_tables.py
"""
import json
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
DATA = ROOT / "docs/utopia/data/a3b"
OUT = ROOT / "docs/utopia/TABLES-A3b.md"
WIDTHS = (393, 768, 1024, 1440, 1920, 2560)
TAGS = ("H1", "H2", "H3", "H4", "H5", "H6")


def load(page, width, state, kind):
    path = DATA / f"{page}-{width}-{state}-{kind}.json"
    if not path.exists():
        return None
    data = json.loads(path.read_text())
    assert data["viewport"]["width"] == width, path
    return data["rows"]


def px(value):
    return float(value[:-2]) if value.endswith("px") else None


def short(value):
    return f"{px(value):.1f}".rstrip("0").rstrip(".")


def spread(rows, tag):
    sizes = Counter(short(r["fontSize"]) for r in rows if r["tag"] == tag and r["width"] > 0)
    return " · ".join(f"{s}×{n}" if n > 1 else s for s, n in sorted(sizes.items(), key=lambda kv: -float(kv[0])))


def max_delta(a, b):
    pairs = [(px(x["fontSize"]), px(y["fontSize"])) for x, y in zip(a, b) if x["width"] > 0]
    return max(abs(x - y) for x, y in pairs)


def mission(rows):
    i = next(n for n, r in enumerate(rows) if "Marlide" in r["fontFamily"])
    motto, text = rows[i], rows[i + 1]
    return motto, text


def main():
    out = [
        "# A3b tables: fluid type behind the theme setting, live pages with CSS injected",
        "",
        "Generated by `docs/utopia/tools/a3b_tables.py` from `docs/utopia/data/a3b/*.json` (local, not committed).",
        "Captured 19 Oct 2026, 22:14–22:20 (after the bridge fix in REPORT §A3b), with the approved Orca "
        "browser helper (`.orca/mission-runtime/browser.py`, isolated anonymous profile, sandboxed caller). "
        "Nothing hidden: consent banner and sticky bar render as served.",
        "Computed `font-size` in px. Sizes per tag are the distinct values with their count (visible elements only).",
        "States: **off** = live page (the setting is off, nothing loads); **A3 alone** = the reviewed `kc-fluid.css` "
        "of f176627; **on** = `docs/utopia/inject/fluid-on.css`; **wide** = `docs/utopia/inject/fluid-on-wide.css`.",
        "",
    ]

    out += ["## 1. Unchanged where it must be", "",
            "Largest |on − off| over every measured element (font size, px). 393 and 1440 are the ramp ends; "
            "1920 and 2560 hold the 1440 values while the wide step is off.", "",
            "| Page | Set | 393 | 1440 | 1920 | 2560 |", "|---|---|---|---|---|---|"]
    for page, kinds in (("home", ("head", "body")), ("pdp", ("head", "card"))):
        for kind in kinds:
            cells = []
            for w in (393, 1440, 1920, 2560):
                off, on = load(page, w, "off", kind), load(page, w, "on", kind)
                cells.append(f"{max_delta(off, on):.4f}" if off and on else "–")
            out.append(f"| {page} | {kind} | " + " | ".join(cells) + " |")
    out.append("")

    out += ["## 2. Headings: one scale between 750 and 1439", ""]
    for page in ("home", "pdp"):
        out += [f"### {'Homepage' if page == 'home' else 'Duo PDP'}", "",
                "| Width | State | " + " | ".join(t.lower() for t in TAGS) + " |",
                "|---|---|" + "---|" * len(TAGS)]
        for w in WIDTHS:
            for state in ("off", "a3", "on", "wide"):
                rows = load(page, w, state, "head")
                if rows:
                    label = {"off": "off", "a3": "A3 alone", "on": "**on**", "wide": "wide"}[state]
                    out.append(f"| {w} | {label} | " + " | ".join(spread(rows, t) or "–" for t in TAGS) + " |")
        out.append("")
    out += ["The homepage A3-alone row was measured on a later page load (100-row cap reached), so its counts "
            "differ slightly; the values show the split: Dawn `h2`/`h3` stay 44/36 while token `h2` is 33.7.", ""]

    out += ["## 3. Body (homepage `body, p`) and PDP `body`", "",
            "| Width | home off | home on | home wide | PDP body off | PDP body on |", "|---|---|---|---|---|---|"]
    for w in WIDTHS:
        cells = []
        for state in ("off", "on", "wide"):
            rows = load("home", w, state, "body")
            cells.append(" · ".join(sorted({short(r["fontSize"]) for r in rows if r["width"] > 0},
                                           key=float, reverse=True)) if rows else "–")
        for state in ("off", "on"):
            rows = load("pdp", w, state, "card")
            cells.append(short(rows[0]["fontSize"]) if rows else "–")
        out.append(f"| {w} | " + " | ".join(cells) + " |")
    out.append("")

    out += ["## 4. PDP mission card (`.kc-mission-card-motto` / `.kc-mission-card-text`)", "",
            "Size / line height in px. Today the motto is 28 at every width (h2 below 750, h4 from 750); "
            "the text steps 16/24 → 15/20 at 750.", "",
            "| Width | off motto | off text | A3 alone motto | A3 alone text | **on** motto | **on** text | wide motto | wide text |",
            "|---|---|---|---|---|---|---|---|---|"]
    for w in (393, 749, 750, 768, 1024, 1440, 1920, 2560):
        cells = []
        for state in ("off", "a3", "on", "wide"):
            rows = load("pdp", w, state, "mc") or load("pdp", w, state, "card")
            if rows:
                motto, text = mission(rows)
                cells += [short(motto["fontSize"]),
                          f"{short(text['fontSize'])} / {short(text['lineHeight'])}"]
            else:
                cells += ["–", "–"]
        out.append(f"| {w} | " + " | ".join(cells) + " |")
    out.append("")

    out += ["## 5. Loop texts in the buybox (exposure, Loop CSS untouched)", "",
            "Distinct sizes of the visible Loop elements read by `snippets/loop-widget.css.liquid` "
            "(`.kc-plan-interval-label`, `.kc-plan-subrow`, `.kc-return_care`, `.kc-description-list`, "
            "`.loop-welcome-kit-product-link`, `.kc-pricing-summary__sub-row`, `.kc-reward-row`, `.ft-note`).", "",
            "| Width | off | on | wide |", "|---|---|---|---|"]
    for w in WIDTHS:
        cells = []
        for state in ("off", "on", "wide"):
            rows = load("pdp", w, state, "card")
            if rows:
                i = next(n for n, r in enumerate(rows) if "Marlide" in r["fontFamily"])
                sizes = Counter(short(r["fontSize"]) for r in rows[1:i] if r["width"] > 0)
                cells.append(" · ".join(f"{s}×{n}" for s, n in sorted(sizes.items(), key=lambda kv: -float(kv[0]))))
            else:
                cells.append("–")
        out.append(f"| {w} | " + " | ".join(cells) + " |")
    out.append("")

    seam = [json.loads((DATA / f"pdp-{w}-wide-seam.json").read_text())["rows"] for w in (1439, 1440)]
    out += ["## 6. Seam at 1440 with the wide step on", "",
            f"PDP, {len(seam[0])} elements (mission card, h1–h5, `.text-xl`, body): largest |1440 − 1439| = "
            f"{max_delta(*seam):.3f} px.", ""]
    OUT.write_text("\n".join(out))
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
