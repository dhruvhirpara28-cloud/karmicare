#!/usr/bin/env python3
"""Write docs/utopia/adoption-preview.css: an evaluation layer, never shipped.

It simulates two handoffs from docs/utopia/REPORT.md on top of assets/kc-fluid.css so
the end state can be measured on the live pages (measure.mjs --css a,b):
  1. Dawn's settings-driven sizes (--font-h1-size-mobile/-desktop ... body, xl) made
     fluid. Where the setting equals the Figma role at both ends, it points at the kc
     token (and so gets the wide step); otherwise its own mobile and desktop values are
     interpolated 393 -> 1440 with the same clamp() as generate.py. No new values.
  2. The page column (Dawn .page-width) set to the Figma container: --page-width =
     --kc-fluid-container-max + both page gutters (1440 at 1440, 1592 at 1920).
Values come from config/settings_data.json (read only) and the schema defaults.

Run from the repo root:  python3 docs/utopia/tools/adoption_preview.py
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / "docs/utopia"))
from generate import clamp, MOBILE_W, DESKTOP_W  # noqa: E402

OUT = ROOT / "docs/utopia/adoption-preview.css"
FIGMA = json.loads((ROOT / "docs/utopia/kc-tokens.json").read_text())["collections"]["responsive"]["vars"]

# Dawn variable stem -> (settings id stem, Figma role it plays)
DAWN = [
    ("font-h1-size", "h1_font_size", "h1"),
    ("font-h2-size", "h2_font_size", "h2"),
    ("font-h3-size", "h3_font_size", "h3"),
    ("font-h4-size", "h4_font_size", "h4"),
    ("font-h5-size", "h5_font_size", "h5"),
    ("font-h6-size", "h6_font_size", "h6"),
    ("size-xl", "xl_font_size", "body-lg"),
    ("font-body-size", "body_font_size", "body-md"),
    ("font-body-small-size", "body_small_font_size", "label-lg"),
]


def settings():
    raw = (ROOT / "config/settings_data.json").read_text()
    current = json.loads(re.sub(r"^\s*/\*.*?\*/", "", raw, flags=re.S))["current"]
    defaults = {}
    for group in json.loads((ROOT / "config/settings_schema.json").read_text()):
        for s in group.get("settings", []):
            if "id" in s and "default" in s:
                defaults[s["id"]] = s["default"]
    return lambda key: current.get(key, defaults.get(key))


def main():
    get = settings()
    lines = [
        "/* ADOPTION PREVIEW: evaluation only, never shipped. Generated by docs/utopia/tools/adoption_preview.py",
        "   from config/settings_data.json. Simulates the Dawn-settings and page-width handoffs in",
        "   docs/utopia/REPORT.md on top of assets/kc-fluid.css. */",
        ":root {",
    ]
    for var, key, role in DAWN:
        mb, dk = get(f"{key}_mobile"), get(f"{key}_desktop")
        fig_dk, fig_mb = FIGMA[f"{role}/text size"]
        if (mb, dk) == (fig_mb, fig_dk):
            value, note = f"var(--kc-responsive-{role}-text-size)", f"setting {mb}/{dk} = Figma {role}"
        else:
            value, note = clamp(mb, dk, MOBILE_W, DESKTOP_W), f"setting {mb}/{dk}, Figma {role} is {fig_mb}/{fig_dk}"
        lines.append(f"  --{var}-mobile: {value}; /* {note} */")
        lines.append(f"  --{var}-desktop: var(--{var}-mobile);")
    lines += [
        "  --page-width: calc(var(--kc-fluid-container-max) + 2 * var(--page-gutter)); "
        f"/* setting page_width {get('page_width')} */",
        "}",
        "",
    ]
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
