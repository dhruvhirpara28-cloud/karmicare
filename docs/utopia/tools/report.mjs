#!/usr/bin/env node
// Turn docs/utopia/data/<page>-<label>.json into the tables in docs/utopia/TABLES.md.
//   node docs/utopia/tools/report.mjs [afterLabel]
// Text elements are matched across runs by section + selector + own text + occurrence.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../..');
const AFTER = process.argv[2] || 'after';
const PAGES = ['home', 'pdp'];
const load = (page, label) => {
  const f = path.join(ROOT, 'docs/utopia/data', `${page}-${label}.json`);
  return existsSync(f) ? JSON.parse(readFileSync(f, 'utf8')) : null;
};

function keyed(vp) {
  const seen = new Map();
  const out = new Map();
  for (const t of vp.texts) {
    const base = `${t.section}|${t.sel}|${t.text}`;
    const n = (seen.get(base) || 0) + 1;
    seen.set(base, n);
    out.set(`${base}|${n}`, t);
  }
  return out;
}

function classify(value) {
  if (!value) return { kind: 'unknown', role: '?' };
  let m = value.match(/var\(--kc-responsive-([a-z0-9-]+?)-text-size/);
  if (m) return { kind: 'kc token', role: m[1] };
  m = value.match(/var\(--kc-buybox-([a-z0-9-]+)/);
  if (m) return { kind: 'buybox token', role: 'buybox ' + m[1] };
  m = value.match(/var\(--(font-[a-z0-9-]+|size-xl-[a-z]+|extra_small_font_size_all)/);
  if (m) return { kind: 'Dawn setting', role: m[1].replace(/-(mobile|desktop)$/, '') };
  m = value.match(/var\(--([a-zA-Z0-9_-]+)/);
  if (m) return { kind: 'local variable', role: '--' + m[1] };
  if (/^(inherit|[\d.]+(em|%))$/.test(value.trim())) return { kind: 'relative', role: value.trim() };
  return { kind: 'literal', role: value.trim() };
}

// Repo file and line for an attributed declaration. Source-map lines are checked; when
// the line does not hold the property (or the rule is inline in the HTML), the first
// selector of the rule is looked up instead.
const fileCache = new Map();
function repoLines(rel) {
  if (!fileCache.has(rel)) {
    const abs = path.join(ROOT, rel);
    fileCache.set(rel, existsSync(abs) ? readFileSync(abs, 'utf8').split('\n') : null);
  }
  return fileCache.get(rel);
}
const grepCache = new Map();
function locate(attr, prop = 'font-size') {
  if (!attr) return '?';
  if (attr.file === 'style attribute') return 'style attribute';
  let rel = (attr.file || '').split('?')[0].replace(/^\//, '');
  const lines = rel && rel !== 'inline' ? repoLines(rel) : null;
  if (lines && attr.line && (lines[attr.line - 1] || '').includes(prop)) return `${rel}:${attr.line}`;
  const first = attr.selector.split(',')[0].trim().replace(/#shopify-section-[^ ]+/, '').trim();
  const needle = first.split(/[\s>+~]+/).filter(Boolean).pop() || first;
  const tryFile = (rf) => {
    const ls = repoLines(rf);
    if (!ls) return null;
    for (let i = 0; i < ls.length; i++) {
      if (!ls[i].includes(needle)) continue;
      for (let j = i; j < Math.min(ls.length, i + 40); j++) {
        if (ls[j].includes(prop + ':') && ls[j].includes(attr.value.slice(0, 18))) return `${rf}:${j + 1}`;
        if (j > i && ls[j].includes('}')) break;
      }
    }
    return null;
  };
  if (lines) {
    const hit = tryFile(rel);
    if (hit) return hit;
  }
  const gkey = needle + '|' + attr.value;
  if (!grepCache.has(gkey)) {
    let files = [];
    try {
      files = execFileSync('git', ['grep', '-l', '-F', needle, '--', 'sections', 'snippets', 'layout', 'assets', 'blocks'],
        { cwd: ROOT, encoding: 'utf8' }).trim().split('\n').filter(Boolean);
    } catch { files = []; }
    let hit = null;
    for (const f of files) if ((hit = tryFile(f))) break;
    grepCache.set(gkey, hit || (rel ? `${rel} (${needle})` : `inline (${needle})`));
  }
  return grepCache.get(gkey);
}

const median = (xs) => {
  const s = [...xs].sort((a, b) => a - b);
  return s.length ? s[Math.floor(s.length / 2)] : null;
};
const fmt = (n) => (n === null || n === undefined ? '–' : Number.isInteger(n) ? String(n) : n.toFixed(1));
const delta = (a, b) => {
  if (a === null || b === null) return '';
  const d = Math.round((b - a) * 10) / 10;
  return d === 0 ? '' : ` (${d > 0 ? '+' : ''}${fmt(d)})`;
};

const md = [];
md.push(`# A3 tables (generated by docs/utopia/tools/report.mjs from docs/utopia/data, "${AFTER}" run)`, '');

for (const page of PAGES) {
  const before = load(page, 'before');
  const after = load(page, AFTER);
  if (!before) continue;
  if (!after) {
    md.push(`## ${page === 'home' ? 'Homepage' : 'Duo PDP'}`, '', `No "${AFTER}" run for this page (pending browser route).`, '');
    continue;
  }
  const widths = before.viewports.map((v) => v.vw);
  md.push(`## ${page === 'home' ? 'Homepage' : 'Duo PDP'}`, '');

  // Role groups from the 1440 attribution (the desktop frame), applied at every width
  // via the matching key; sizes are the median computed size per group and width.
  const groups = new Map();
  for (const vp of before.viewports) {
    const aft = after?.viewports.find((v) => v.vw === vp.vw);
    const aKeyed = aft ? keyed(aft) : new Map();
    for (const [k, t] of keyed(vp)) {
      if (t.offscreen) continue;
      const attr = vp.attribution?.[t.i]?.['font-size'];
      const c = classify(attr?.value);
      const gk = `${c.kind}|${c.role}`;
      if (!groups.has(gk)) groups.set(gk, { ...c, sizes: {}, after: {}, lh: {}, lhAfter: {}, where: new Set(), sections: new Set(), count: {} });
      const g = groups.get(gk);
      (g.sizes[vp.vw] ||= []).push(t.fs);
      if (typeof t.lh === 'number') (g.lh[vp.vw] ||= []).push(t.lh);
      g.count[vp.vw] = (g.count[vp.vw] || 0) + 1;
      g.sections.add(t.section);
      if (vp.vw === 1440 || vp.vw === 393) g.where.add(locate(attr));
      const a = aKeyed.get(k);
      if (a) {
        (g.after[vp.vw] ||= []).push(a.fs);
        if (typeof a.lh === 'number') (g.lhAfter[vp.vw] ||= []).push(a.lh);
      }
    }
  }
  const order = ['kc token', 'buybox token', 'Dawn setting', 'local variable', 'relative', 'literal', 'unknown'];
  const sorted = [...groups.values()].sort((a, b) => order.indexOf(a.kind) - order.indexOf(b.kind)
    || (median(b.sizes[1440] || b.sizes[widths[0]]) || 0) - (median(a.sizes[1440] || a.sizes[widths[0]]) || 0));

  md.push('### Font size per source, before → after (px, median per group; Δ in brackets)', '');
  md.push(`| source | role / value | n@1440 | ${widths.join(' | ')} |`);
  md.push(`|---|---|---|${widths.map(() => '---').join('|')}|`);
  for (const g of sorted) {
    const cells = widths.map((w) => {
      const b = median(g.sizes[w] || []);
      const a = median(g.after[w] || []);
      if (b === null) return '–';
      return a === null || a === b ? fmt(b) : `${fmt(b)} → ${fmt(a)}${delta(b, a)}`;
    });
    md.push(`| ${g.kind} | \`${g.role}\` | ${g.count[1440] || 0} | ${cells.join(' | ')} |`);
  }
  md.push('');

  md.push('### Line height per source, before → after (px, median)', '');
  md.push(`| source | role / value | ${widths.join(' | ')} |`);
  md.push(`|---|---|${widths.map(() => '---').join('|')}|`);
  for (const g of sorted) {
    const changed = widths.some((w) => median(g.lh[w] || []) !== median(g.lhAfter[w] || []));
    if (!changed) continue;
    const cells = widths.map((w) => {
      const b = median(g.lh[w] || []);
      const a = median(g.lhAfter[w] || []);
      if (b === null) return '–';
      return a === null || a === b ? fmt(b) : `${fmt(b)} → ${fmt(a)}`;
    });
    md.push(`| ${g.kind} | \`${g.role}\` | ${cells.join(' | ')} |`);
  }
  md.push('');

  md.push('### Where each source is declared (393 and 1440 attribution)', '');
  md.push('| source | role / value | sections | declared at |');
  md.push('|---|---|---|---|');
  for (const g of sorted) {
    md.push(`| ${g.kind} | \`${g.role}\` | ${[...g.sections].join(', ')} | ${[...g.where].slice(0, 6).join('<br>')} |`);
  }
  md.push('');

  // Body copy below 14 px on the smallest width, and long lines from 1440 up.
  const vp393 = before.viewports.find((v) => v.vw === 393);
  const a393 = after?.viewports.find((v) => v.vw === 393);
  const aK393 = a393 ? keyed(a393) : new Map();
  const small = [];
  for (const [k, t] of keyed(vp393)) {
    if (t.offscreen || t.chars < 25) continue;
    const a = aK393.get(k);
    if (t.fs < 14 || (a && a.fs < 14)) {
      const attr = vp393.attribution?.[t.i]?.['font-size'];
      small.push(`| ${t.section} | \`${t.sel}\` | ${fmt(t.fs)} → ${a ? fmt(a.fs) : '?'} | ${t.text.slice(0, 40)} | \`${attr?.value || '?'}\` ${locate(attr)} |`);
    }
  }
  md.push('### Running text under 14 px at 393 (25+ characters), before → after', '');
  md.push('| section | element | px | text | declared |', '|---|---|---|---|---|', ...[...new Set(small)], '');

  md.push('### Lines over 75 characters from 1440 up (capacity of the text box; actual where it wraps)', '');
  md.push('| width | section | element | px | capacity before → after | actual | text | declared |');
  md.push('|---|---|---|---|---|---|---|---|');
  for (const vp of before.viewports.filter((v) => v.vw >= 1440)) {
    const aK = keyed(after?.viewports.find((v) => v.vw === vp.vw) || { texts: [] });
    for (const [k, t] of keyed(vp)) {
      if (t.offscreen || t.chars < 80 || t.fs > 24) continue;
      const a = aK.get(k);
      if (t.cplCapacity <= 75 && (!a || a.cplCapacity <= 75)) continue;
      const attr = vp.attribution?.[t.i]?.['font-size'];
      md.push(`| ${vp.vw} | ${t.section} | \`${t.sel}\` | ${fmt(t.fs)} | ${t.cplCapacity} → ${a ? a.cplCapacity : '?'} | ${t.cplActual ?? '1 line'} | ${t.text.slice(0, 32)} | ${locate(attr)} |`);
    }
  }
  md.push('');

  md.push('### Section edges (left edge of text / media, px from the viewport edge; before → after where they differ)', '');
  md.push(`| section | ${widths.map((w) => `${w} text`).join(' | ')} |`);
  md.push(`|---|${widths.map(() => '---').join('|')}|`);
  const names = before.viewports.at(-1).sections.map((s) => s.name);
  const edge = (s) => (s ? `${s.textLeft ?? '–'}${s.mediaLeft !== null ? ` / m ${s.mediaLeft}` : ''}` : '–');
  for (const n of names) {
    const cells = widths.map((w) => {
      const b = edge(before.viewports.find((v) => v.vw === w).sections.find((x) => x.name === n));
      const a = edge(after.viewports.find((v) => v.vw === w)?.sections.find((x) => x.name === n));
      return a === '–' || a === b ? b : `${b} → ${a}`;
    });
    md.push(`| ${n} | ${cells.join(' | ')} |`);
  }
  md.push('');

  md.push('### Grids and rows from 1440 up (before → after where they differ)', '');
  md.push('| width | section | element | width | cols | gap | children |', '|---|---|---|---|---|---|---|');
  const gridRows = (vp) => {
    const seen = new Map();
    const rows = [];
    for (const g of vp?.grids || []) {
      if (g.section === 'header') continue;
      const base = `${g.section}|${g.sel}`;
      const n = (seen.get(base) || 0) + 1;
      seen.set(base, n);
      rows.push([`${base}|${n}`, g]);
    }
    return rows;
  };
  for (const vp of before.viewports.filter((v) => v.vw >= 1440)) {
    const aMap = new Map(gridRows(after.viewports.find((v) => v.vw === vp.vw)));
    const printed = new Set();
    for (const [k, g] of gridRows(vp)) {
      const a = aMap.get(k);
      const kids = g.childWidths.join(' / ');
      const aKids = a ? a.childWidths.join(' / ') : kids;
      const line = `| ${vp.vw} | ${g.section} | \`${g.sel.replace(/#[A-Za-z0-9_-]+/, '')}\` | ${a && a.width !== g.width ? `${g.width} → ${a.width}` : g.width} | ${g.columns} | ${g.gap} | ${aKids !== kids ? `${kids} → ${aKids}` : kids} |`;
      if (printed.has(line)) continue;
      printed.add(line);
      md.push(line);
    }
  }
  md.push('');

  md.push('### Media served smaller than drawn on a 2x screen (rendered × 2 > largest source)', '');
  md.push('| width | section | element | file | drawn | largest source | factor @2x |', '|---|---|---|---|---|---|---|');
  for (const vp of before.viewports) {
    for (const m of vp.media) {
      const best = Math.max(m.maxSrc, m.natural);
      if (!best || /\.svg$/.test(m.src)) continue;
      const f = (m.w * 2) / best;
      if (f > 1.05) md.push(`| ${vp.vw} | ${m.section} | \`${m.sel}\` | ${m.src} | ${m.w}×${m.h} | ${best} | ${f.toFixed(2)} |`);
    }
  }
  md.push('');
  md.push(`Measured ${before.measured} (before) / ${after?.measured || '–'} (${AFTER}); ch ratio ${before.viewports[0].chRatio ?? '–'}; theme ${JSON.stringify(before.viewports[0].theme)}.`, '');
}

const outName = AFTER === 'after' ? 'TABLES.md' : `TABLES-${AFTER}.md`;
writeFileSync(path.join(ROOT, 'docs/utopia', outName), md.join('\n'));
console.log(`wrote docs/utopia/${outName}`, md.length, 'lines');
