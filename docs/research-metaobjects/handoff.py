"""Write TRANSLATIONS.md: the source-copy handoff for the research cards (R67).

Reads the five card blocks of templates/index.json (the EN source at b0bb4fb) and the
NL/FR localization batches (homepage batch-01, PDP batch-02), and lists per entry and
field the EN text, the NL and FR translations with their statuses, so the source-copy
lane can move them onto the research_card metaobject entries. Run from the repo root:

    python3 docs/research-metaobjects/handoff.py
"""
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SECTION = 'research_behind_system_EkjATL'
CARDS = [  # block id in the templates → entry handle in admin (created 24 Oct 2026)
    ('card_bDxUVT', 'kulal-2016'),
    ('card_yMiD9D', 'lei-hu-2025'),
    ('card_fmFMFd', 'janakiram-2017'),
    ('card_Hi7YUD', 'vano-2018'),
    ('card_JeERX6', 'alli-2019'),
]
TEXT_FIELDS = ['subheading', 'heading', 'subtext', 'result_label', 'result_text',
               'method_label', 'method_text', 'link_label', 'image_badge']
OTHER_FIELDS = ['link_url', 'logo', 'image']


def load_batch(lang, batch):
    with open(f'{ROOT}/docs/localization/{lang}/{batch}.json') as f:
        return {e['id']: e for e in json.load(f)['entries']}


def load_template(path):
    with open(path) as f:
        text = f.read()
    text = re.sub(r'^\s*/\*.*?\*/\s*', '', text, count=1, flags=re.S)  # the editor's comment header
    return json.loads(text)['sections'][SECTION]['blocks']


def cell(entry, lang):
    if not entry:
        return '—', '—'
    value = entry.get(lang)
    return (value if value is not None else '(held)'), entry.get('status', '')


def main():
    nl = load_batch('nl', 'batch-01-homepage')
    fr = load_batch('fr', 'batch-01-homepage')
    nl_pdp = load_batch('nl', 'batch-02-pdp')
    fr_pdp = load_batch('fr', 'batch-02-pdp')
    home = load_template(f'{ROOT}/templates/index.json')
    pdp = load_template(f'{ROOT}/templates/product.subscription-item.json')

    out = []
    out.append('# Research cards · translation handoff (R67)\n')
    out.append('Generated by `docs/research-metaobjects/handoff.py` from `templates/index.json` (the EN source '
               'for the metaobject entries), `docs/localization/nl/batch-01-homepage.json` and '
               '`docs/localization/fr/batch-01-homepage.json`. How to use it: `SWITCH-OVER.md` §6.\n')
    out.append('Source ids in the batches: `index:' + SECTION + '/<block>/<field>` (homepage) and '
               '`product.subscription-item:' + SECTION + '/<block>/<field>` (PDP). The PDP batch-02 entries '
               'carry the same translations; a PDP EN that differs from the homepage EN is noted in the last column.\n')
    out.append('## Text fields\n')
    out.append('| Entry handle | Field | EN (homepage, b0bb4fb) | NL | NL status | FR | FR status | Block · notes |')
    out.append('|---|---|---|---|---|---|---|---|')
    pdp_differs = []
    for block, handle in CARDS:
        for field in TEXT_FIELDS:
            en = home[block]['settings'].get(field, '')
            en_pdp = pdp[block]['settings'].get(field, '')
            hid = f'index:{SECTION}/{block}/{field}'
            pid = f'product.subscription-item:{SECTION}/{block}/{field}'
            nl_v, nl_s = cell(nl.get(hid), 'nl')
            fr_v, fr_s = cell(fr.get(hid), 'fr')
            note = block
            if en_pdp != en:
                note += f' · PDP EN: "{en_pdp}"'
                pdp_differs.append((handle, field, en, en_pdp))
            for lang, batch in (('nl', nl_pdp), ('fr', fr_pdp)):
                p = batch.get(pid)
                h = (nl if lang == 'nl' else fr).get(hid)
                if p and h and p.get(lang) != h.get(lang):
                    note += f' · PDP {lang.upper()} differs: "{p.get(lang)}"'
            out.append(f'| {handle} | `{field}` | {en} | {nl_v} | {nl_s} | {fr_v} | {fr_s} | {note} |')

    out.append('\n## Fields that are not translated\n')
    out.append('| Entry handle | Field | Homepage | PDP |')
    out.append('|---|---|---|---|')
    for block, handle in CARDS:
        for field in OTHER_FIELDS:
            a = home[block]['settings'].get(field, '') or '(empty)'
            b = pdp[block]['settings'].get(field, '') or '(empty)'
            out.append(f'| {handle} | `{field}` | {a} | {b}{" · **differs**" if a != b else ""} |')

    out.append('\n## Statuses\n')
    counts = {}
    for block, _ in CARDS:
        for field in TEXT_FIELDS:
            for lang, batch in (('NL', nl), ('FR', fr)):
                e = batch.get(f'index:{SECTION}/{block}/{field}')
                key = (lang, e.get('status', 'missing') if e else 'missing')
                counts[key] = counts.get(key, 0) + 1
    for (lang, status), n in sorted(counts.items()):
        out.append(f'- {lang} `{status}`: {n} fields')
    out.append('')

    with open(f'{ROOT}/docs/research-metaobjects/TRANSLATIONS.md', 'w') as f:
        f.write('\n'.join(out))
    print(f'wrote docs/research-metaobjects/TRANSLATIONS.md · {len(CARDS) * len(TEXT_FIELDS)} text fields · '
          f'PDP EN differs: {[(h, f) for h, f, _, _ in pdp_differs]}')


if __name__ == '__main__':
    main()
